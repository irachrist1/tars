import { mkdir, writeFile, readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { detectWorkFolder, workspaceDir, indexStore, readBootstrap } from './paths.mjs';
import { runNodeScript, indexerScript, scanScript, connectorsScript } from './run-script.mjs';

export async function resolveWorkRoot(seedPath, override) {
  if (override) return override;
  if (seedPath) {
    try {
      const seed = await readFile(seedPath, 'utf8');
      const m = seed.match(/work_folder:\s*(.+)/);
      if (m && !m[1].includes('to be')) return m[1].trim();
    } catch {}
  }
  return detectWorkFolder();
}

export async function bootstrapFirstRun({ workRoot, skillDest, toolsJson, progress = console.log }) {
  if (!workRoot) return { ok: false, error: 'no work folder detected' };

  const ws = workspaceDir(workRoot);
  const store = indexStore(workRoot);
  await mkdir(ws, { recursive: true });

  const existing = await readBootstrap(workRoot);
  if (existing?.completedAt) return { ok: true, skipped: true, ...existing };

  progress(`  Scanning ${workRoot}…`);
  const scan = runNodeScript(scanScript(), ['--root', workRoot, '--json']);
  let scanData = null;
  if (scan.ok && scan.stdout) {
    try { scanData = JSON.parse(scan.stdout); } catch {}
  }

  progress('  Building local index…');
  const index = runNodeScript(indexerScript(), ['build', '--root', workRoot, '--json']);

  progress('  Mapping connectors…');
  const connArgs = ['--json'];
  if (toolsJson) connArgs.push('--tools', toolsJson);
  const conn = runNodeScript(connectorsScript(), connArgs);
  let connMd = conn.stdout || '';
  if (connMd && !connMd.startsWith('{')) {
    await writeFile(join(ws, 'CONNECTORS.md'), connMd.trim() + '\n', 'utf8');
  } else if (conn.ok && conn.stdout) {
    try {
      const data = JSON.parse(conn.stdout);
      const lines = ['# Connectors — your connected context surface', `Detected on ${new Date().toISOString().slice(0, 10)}.`, ''];
      for (const c of data.connected || []) {
        lines.push(`- **${c.name}** — ${c.cat}. Holds ${c.holds}. Open for: ${c.use}.`);
      }
      connMd = lines.join('\n');
      await writeFile(join(ws, 'CONNECTORS.md'), connMd + '\n', 'utf8');
    } catch {}
  }

  const seedNote = `# Bootstrap seed
Generated by \`tars open\` on ${new Date().toISOString().slice(0, 10)}.
The skill should adopt this and skip re-detection.

- work_folder: ${workRoot}
- index_store: ${store}
- scan_hubs: ${scanData?.areas?.length ?? 0}
- index_docs: ${index.ok ? '(built)' : '(failed — retry with tars index build)'}
- connectors_seeded: ${Boolean(connMd)}
`;

  const bootstrap = {
    workRoot,
    workspace: ws,
    indexStore: store,
    scan: scanData,
    indexBuilt: index.ok,
    connectorsSeeded: Boolean(connMd),
    completedAt: new Date().toISOString(),
  };

  await writeFile(join(ws, 'onboarding-seed.md'), seedNote, 'utf8');
  await writeFile(join(ws, 'workspace-bootstrap.json'), JSON.stringify(bootstrap, null, 2) + '\n', 'utf8');

  if (skillDest) {
    try {
      await stat(join(skillDest, 'onboarding-seed.md'));
    } catch {
      await writeFile(join(skillDest, 'onboarding-seed.md'), seedNote, 'utf8');
    }
  }

  return { ok: true, ...bootstrap };
}

export async function needsBootstrap(workRoot) {
  const ws = workspaceDir(workRoot);
  if (!ws) return true;
  try {
    await stat(join(ws, 'workspace-bootstrap.json'));
    return false;
  } catch {
    try {
      await stat(join(ws, 'MAP.md'));
      return false;
    } catch { return true; }
  }
}
